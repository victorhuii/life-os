import assert from "node:assert/strict";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import ts from "typescript";
const dir = new URL('../.sites-runtime/calendar-tests/', import.meta.url);
mkdirSync(dir, { recursive: true });
const target = new URL('calendar-visibility.mjs', dir);
writeFileSync(target, ts.transpileModule(readFileSync(new URL('../lib/calendar-visibility.ts', import.meta.url), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText);
const { calendarEventKey, eventHasEnded, readHiddenEvents } = await import(pathToFileURL(target.pathname));
const now = Date.parse('2026-10-19T12:00:00-07:00');
const event = { id:'one', account:'huiv@berkeley.edu', calendarId:'classes', start:'2026-10-19T11:00:00-07:00', end:'2026-10-19T12:30:00-07:00' };
assert.equal(eventHasEnded(event, now), false, 'Ongoing events remain visible');
assert.equal(eventHasEnded(event, Date.parse(event.end)), true, 'Hide at the exact end');
assert.equal(eventHasEnded({ ...event, end:'invalid' }, now), false, 'Bad timestamps do not silently hide events');
const allDay = { ...event, allDay:true, start:'2026-10-19T00:00:00-07:00', end:'2026-10-20T00:00:00-07:00' };
assert.equal(eventHasEnded(allDay, Date.parse('2026-10-19T23:59:59-07:00')), false);
assert.equal(eventHasEnded(allDay, Date.parse(allDay.end)), true, 'All-day events use their exclusive end');
assert.equal(eventHasEnded({ ...event, end:'2026-10-19T19:00:00Z' }, now), true, 'Compare instants across timezone offsets');
assert.notEqual(calendarEventKey(event), calendarEventKey({ ...event, calendarId:'meetings' }), 'Same provider ID in another calendar stays independent');
assert.notEqual(calendarEventKey(event), calendarEventKey({ ...event, id:'recurrence2' }));
const key = calendarEventKey(event);
assert.deepEqual([...readHiddenEvents(JSON.stringify([key, key, 5, null]))], [key]);
for (const corrupt of [null, 'oops', '{}', 'null']) assert.equal(readHiddenEvents(corrupt).size, 0);
assert.equal(readHiddenEvents(JSON.stringify(['x'.repeat(2049)])).size, 0);
console.log('PASS: ongoing events, exact end, all-day exclusive end, timezone offsets, scoped event identities and corrupt local storage.');
